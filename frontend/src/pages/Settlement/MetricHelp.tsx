export function metricLabel(label: ReactNode): ReactNode {
  if (typeof label !== 'string') return label;
  const explanation =
    explanations[label] ||
    Object.entries(explanations).find(([key]) => label.endsWith(key))?.[1];
  if (!explanation) return label;
  return (
    <span style={{ whiteSpace: 'nowrap' }}>
      {label}
      <Tooltip
        title={explanation}
        trigger={['hover', 'focus', 'click']}
        overlayStyle={{ maxWidth: 380 }}
      >
        <span
          tabIndex={0}
          role="button"
          aria-label={`${label}说明`}
          onClick={(event) => event.stopPropagation()}
          style={{
            marginLeft: 6,
            color: '#8c8c8c',
            cursor: 'help',
            display: 'inline-flex',
            verticalAlign: 'middle',
          }}
        >
          <ExclamationCircleOutlined />
        </span>
      </Tooltip>
    </span>
  );
}
